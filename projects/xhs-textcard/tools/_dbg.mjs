import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
const ROOT = '/home/user/image/projects/xhs-textcard';
const MIME={'.html':'text/html; charset=utf-8','.js':'text/javascript','.css':'text/css','.json':'application/json','.png':'image/png','.jpg':'image/jpeg'};
const server=createServer(async(req,res)=>{try{const p=decodeURIComponent(new URL(req.url,'http://x').pathname);let f=path.join(ROOT,p==='/'?'/editor.html':p);if(!existsSync(f)){res.writeHead(404).end('nf');return;}res.writeHead(200,{'content-type':MIME[path.extname(f)]||'application/octet-stream'});res.end(await readFile(f));}catch(e){res.writeHead(500).end(String(e));}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`;
const {chromium}=await import('playwright');
const b=await chromium.launch({executablePath:'/tmp/chromium'});
const pg=await b.newPage();
await pg.route('**/*',r=>r.request().url().startsWith(base)?r.continue():r.fulfill({status:200,body:''}));
pg.on('pageerror',e=>console.log('PAGEERROR:',String(e).split('\n')[0]));
pg.on('console',m=>{ if(m.type()==='error') console.log('CONSOLE.ERR:',m.text().slice(0,200)); });
await pg.goto(base+'/editor.html',{waitUntil:'domcontentloaded'});
await pg.waitForTimeout(4000);
console.log('globals:', await pg.evaluate(()=>Object.keys(window).filter(k=>/^(app|App|CanvasRenderer|TextSplitter)/.test(k))));
console.log('typeof app:', await pg.evaluate(()=>typeof app));
