console.log('typeof marked:', await pg.evaluate(()=>typeof marked));
console.log('typeof Pickr:', await pg.evaluate(()=>typeof Pickr));
console.log('previewCount:', await pg.evaluate(()=>document.querySelector('#preview-count')?.textContent));
